#!/usr/bin/env python3
"""Day-zero setup for a fresh GBA decomp from baserom.gba.

  python3 tools/decomp/init_project.py [--name my_game] [--game-name "My Game"]

Reads the cartridge header, writes project.mk / rom.sha1 / <name>.toml, emits
the "no matched functions yet" ROM scaffold (asm/rom.s = whole baserom as one
.incbin) and leaves `make compare` green. Safe to re-run; it only overwrites
the files listed above.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_") or "game"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--name", help="output file stem (default: slug of the header title)")
    ap.add_argument("--game-name", help="display name for reports")
    ap.add_argument("--skip-make", action="store_true", help="do not run `make compare`")
    args = ap.parse_args()

    rom = ROOT / "baserom.gba"
    if not rom.is_file():
        print("error: put the clean dump at ./baserom.gba first", file=sys.stderr)
        return 1
    data = rom.read_bytes()
    if len(data) < 0xC0 or data[0xB2] != 0x96:
        print("error: baserom.gba has no valid GBA header (fixed byte 0xB2 != 0x96)", file=sys.stderr)
        return 1
    title = data[0xA0:0xAC].decode("ascii", "replace").rstrip("\0 ")
    code = data[0xAC:0xB0].decode("ascii", "replace")
    maker = data[0xB0:0xB2].decode("ascii", "replace")
    rev = data[0xBC]
    name = args.name or slug(title)
    game = args.game_name or title.title()

    (ROOT / "project.mk").write_text(
        "# Per-game settings; see tools/decomp/projcfg.py. Generated by init_project.py.\n"
        f"FILE_NAME  := {name}\n"
        f"GAME_NAME  := {game}\n"
        f"TITLE      := {title}\n"
        f"GAME_CODE  := {code}\n"
        f"MAKER_CODE := {maker}\n"
        f"REVISION   := {rev}\n"
        "\n"
        "# Optional: ROM address of libgcc __divsi3 (the `bl` target of a signed `x / n`).\n"
        "# `_call_via_rN` thunks are found in the baserom automatically (tools/decomp/libgcc.py).\n"
        "DIVSI3_ADDR :=\n"
    )
    sha = hashlib.sha1(data).hexdigest()
    (ROOT / "rom.sha1").write_text(f"{sha}  {name}.gba\n")
    toml = ROOT / f"{name}.toml"
    if not toml.exists():
        toml.write_text(
            "# Function renames for tools/decomp (generated view: edit analysis/symbols.json\n"
            "# via tools/decomp/symbols.py, never by hand).\n\n[renames]\n"
        )
    print(f"init: {name}  code={code} maker={maker} rev={rev} size={len(data):#x} sha1={sha}")

    (ROOT / "build").mkdir(exist_ok=True)
    manifest = ROOT / "analysis" / "matched.json"
    if not manifest.exists():
        manifest.write_text(json.dumps({"functions": []}))
    for cmd in (
        [sys.executable, "tools/decomp/gen_rom_layout.py"],
        [sys.executable, "tools/decomp/generate_asm.py"],
    ):
        r = subprocess.run(cmd, cwd=ROOT)
        if r.returncode:
            print(f"warning: {' '.join(cmd[1:])} failed (is build_tools.sh done?)", file=sys.stderr)
    if args.skip_make:
        return 0
    return subprocess.run(["make", "compare"], cwd=ROOT).returncode


if __name__ == "__main__":
    raise SystemExit(main())
